// Generate offline WebView resources. No network requests occur in the terminal.
const fs = require('node:fs');
const path = require('node:path');
const root = process.argv[2] || path.resolve(__dirname, '..');
const read = (name, file) => fs.readFileSync(path.join(root, 'node_modules', name, file), 'utf8');
const assets = {
  xtermScript: read('@xterm/xterm', 'lib/xterm.js'),
  fitScript: read('@xterm/addon-fit', 'lib/addon-fit.js'),
  xtermCss: read('@xterm/xterm', 'css/xterm.css'),
};
const out = path.resolve(__dirname, '../src/components/terminal/assets.ts');
fs.writeFileSync(out, '// Generated by scripts/build-terminal-assets.cjs. Includes MIT-licensed xterm.js.\n' + Object.entries(assets).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};`).join('\n') + '\n');
fs.writeFileSync(path.join(path.dirname(out), 'XTERM-LICENSE'), read('@xterm/xterm', 'LICENSE'));
